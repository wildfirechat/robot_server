package cn.wildfirechat.app.chat;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.RowMapper;
import org.springframework.stereotype.Repository;
import org.springframework.util.StringUtils;

import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;

/**
 * 聊天记录仓储。使用 JdbcTemplate 实现，生产使用 PostgreSQL。
 */
@Repository
public class ChatMessageRepository {
    private static final Logger LOG = LoggerFactory.getLogger(ChatMessageRepository.class);

    private static final String SELECT_COLUMNS =
            "SELECT id, conv_type, conv_target, sender, msg_role, content, send_time FROM chat_message";

    private static final RowMapper<ChatMessage> ROW_MAPPER = new RowMapper<ChatMessage>() {
        @Override
        public ChatMessage mapRow(ResultSet rs, int rowNum) throws SQLException {
            ChatMessage message = new ChatMessage();
            message.setId(rs.getLong("id"));
            message.setConvType(rs.getInt("conv_type"));
            message.setConvTarget(rs.getString("conv_target"));
            message.setSender(rs.getString("sender"));
            message.setRole(rs.getString("msg_role"));
            message.setContent(rs.getString("content"));
            message.setSendTime(rs.getTimestamp("send_time").getTime());
            return message;
        }
    };

    private final JdbcTemplate jdbcTemplate;

    public ChatMessageRepository(JdbcTemplate jdbcTemplate) {
        this.jdbcTemplate = jdbcTemplate;
        initSchema();
    }

    /**
     * 建表。应用启动时自动执行，表已存在时不会重复创建。
     */
    private void initSchema() {
        jdbcTemplate.execute("CREATE TABLE IF NOT EXISTS chat_message ("
                + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                + "conv_type INT NOT NULL,"
                + "conv_target VARCHAR(128) NOT NULL,"
                + "sender VARCHAR(128),"
                + "msg_role VARCHAR(16) NOT NULL,"
                + "content TEXT,"
                + "send_time TIMESTAMP NOT NULL)");
        createIndex("idx_chat_message_conv", "conv_type, conv_target, id");
        createIndex("idx_chat_message_role_time", "msg_role, send_time");
        createIndex("idx_chat_message_time", "send_time");
        createIndex("idx_chat_message_sender_id", "sender, id");
    }

    private void createIndex(String name, String columns) {
        try {
            jdbcTemplate.execute("CREATE INDEX IF NOT EXISTS " + name + " ON chat_message (" + columns + ")");
        } catch (Exception e) {
            LOG.debug("聊天记录索引已存在: {}", name);
        }
    }

    /**
     * 保存一条聊天记录。
     *
     * @return 保存成功返回 true；失败仅记录日志，避免影响机器人回复
     */
    public boolean insert(ChatMessage message) {
        try {
            jdbcTemplate.update("INSERT INTO chat_message (conv_type, conv_target, sender, msg_role, content, send_time) "
                            + "VALUES (?, ?, ?, ?, ?, ?)",
                    message.getConvType(),
                    message.getConvTarget(),
                    message.getSender(),
                    message.getRole(),
                    message.getContent(),
                    new java.sql.Timestamp(message.getSendTime()));
            return true;
        } catch (Exception e) {
            LOG.error("保存聊天记录失败, convType:{}, convTarget:{}, role:{}",
                    message.getConvType(), message.getConvTarget(), message.getRole(), e);
            return false;
        }
    }

    /**
     * 删除指定时间之前的聊天记录，用于数据保留策略。
     */
    public int deleteBefore(long cutoffMillis) {
        return jdbcTemplate.update("DELETE FROM chat_message WHERE send_time < ?",
                new java.sql.Timestamp(cutoffMillis));
    }

    /**
     * 管理后台分页查询。
     * sender 非空时按发送者过滤；convType/convTarget 同时非空时按会话过滤。
     */
    public ChatMessagePage page(int requestedPage, int requestedSize, String sender,
                                Integer convType, String convTarget) {
        int size = Math.max(10, Math.min(100, requestedSize));
        int page = Math.max(1, requestedPage);
        StringBuilder where = new StringBuilder();
        List<Object> args = new ArrayList<>();
        if (StringUtils.hasText(sender)) {
            where.append(where.length() == 0 ? " WHERE " : " AND ").append("sender = ?");
            args.add(sender.trim());
        }
        if (convType != null) {
            where.append(where.length() == 0 ? " WHERE " : " AND ").append("conv_type = ?");
            args.add(convType);
            if (StringUtils.hasText(convTarget)) {
                where.append(" AND conv_target = ?");
                args.add(convTarget.trim());
            }
        }
        Long totalValue = jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM chat_message" + where, Long.class, args.toArray());
        long total = totalValue == null ? 0 : totalValue;
        int totalPages = total == 0 ? 1 : (int) ((total + size - 1) / size);
        page = Math.min(page, totalPages);
        List<Object> queryArgs = new ArrayList<>(args);
        queryArgs.add(size);
        queryArgs.add((page - 1) * size);
        List<ChatMessage> messages = jdbcTemplate.query(
                SELECT_COLUMNS + where + " ORDER BY id DESC LIMIT ? OFFSET ?",
                ROW_MAPPER, queryArgs.toArray());
        return new ChatMessagePage(messages, page, size, total);
    }

    /**
     * 最近有消息的会话目标，用于后台筛选下拉；只取最近 limit 个，避免解析大量历史会话名称。
     */
    public List<String> recentConversationTargets(int convType, int limit) {
        int size = Math.max(1, Math.min(200, limit));
        return jdbcTemplate.queryForList(
                "SELECT conv_target FROM chat_message WHERE conv_type = ? "
                        + "GROUP BY conv_target ORDER BY MAX(send_time) DESC LIMIT ?",
                String.class, convType, size);
    }

    /**
     * 最近有消息的用户：发送者 + 单聊目标。用于后台用户搜索的候选集。
     */
    public List<String> recentUserTargets(int limit) {
        int size = Math.max(1, Math.min(500, limit));
        return jdbcTemplate.queryForList(
                "SELECT user_id FROM ("
                        + "SELECT sender AS user_id, MAX(send_time) AS t FROM chat_message "
                        + "WHERE sender IS NOT NULL GROUP BY sender "
                        + "UNION ALL "
                        + "SELECT conv_target AS user_id, MAX(send_time) AS t FROM chat_message "
                        + "WHERE conv_type = 0 GROUP BY conv_target"
                        + ") u GROUP BY user_id ORDER BY MAX(t) DESC LIMIT ?",
                String.class, size);
    }

    /**
     * 查询某个会话最近的若干条记录，返回值按时间正序排列（最早的在前）。
     */
    public List<ChatMessage> findRecent(int convType, String convTarget, int limit) {
        if (limit <= 0) {
            return Collections.emptyList();
        }
        List<ChatMessage> messages = jdbcTemplate.query(
                SELECT_COLUMNS + " WHERE conv_type = ? AND conv_target = ? ORDER BY id DESC LIMIT ?",
                ROW_MAPPER,
                convType, convTarget, limit);
        List<ChatMessage> result = new ArrayList<>(messages);
        Collections.reverse(result);
        return result;
    }
}
